"""Set the "Last update" date at the bottom of each page.

git-revision-date-localized (mkdocs.yml) gets this date wrong in two cases:
  - it skips every commit that renamed a page, even when that commit also edited it, so a page
    moved and edited in the same commit keeps the date of its previous edit
  - it reads git once per `mkdocs serve`, so a page committed while serving keeps its old date
This hook replaces the plugin's date with the date of the last commit that changed the page's
content, reading git on every build:
  - commits that rename and edit a page count; renames without edits (R100) do not
  - while serving, pages with uncommitted changes show the file's modification date
The plugin still formats the date (type, timezone and locale from its settings in mkdocs.yml)
and supplies the build date for pages that are not in git yet.
"""

from pathlib import Path
import subprocess

PLUGIN = "git-revision-date-localized"
META_KEY = "git_revision_date_localized"  # what Material reads for the "Last update" date

_serving = False


def on_startup(*, command, dirty):
    global _serving
    _serving = command == "serve"


def _git(source, *args):
    return subprocess.run(
        ["git", *args, "--", source.name],
        cwd=source.parent,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def _last_content_change(source):
    """Author date (unix time) of the last commit that changed the file's content, like the plugin."""
    # one record per commit, newest first: "\0<unix time>\n\n<status>\t<path>[\t<new path>]"
    log = _git(source, "log", "--follow", "--format=%x00%at", "--name-status")
    for record in log.split("\0")[1:]:
        timestamp, _, change = record.strip().partition("\n")
        if not change.strip().startswith("R100"):  # R100: renamed without edits
            return int(timestamp)
    return None


def on_page_context(context, *, page, config, nav):
    if page.file.abs_src_path is None:  # page generated by a plugin, not a file in git
        return context

    source = Path(page.file.abs_src_path)
    if _serving and _git(source, "status", "--porcelain").strip():
        timestamp = int(source.stat().st_mtime)
    else:
        timestamp = _last_content_change(source)
    if timestamp is None:
        return context

    plugin = config.plugins[PLUGIN]
    dates = plugin.util.get_date_formats_for_timestamp(timestamp, locale=plugin.config["locale"])
    page.meta[META_KEY] = dates[plugin.config["type"]]
    return context
